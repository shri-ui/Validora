import re
from datetime import datetime

from fpdf import FPDF


def _clean(text: str) -> str:
    """Strip light markdown and non-latin chars for PDF output."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text or "")
    text = re.sub(r"\*(.+?)\*", r"\1", text)
    return text.encode("latin-1", "replace").decode("latin-1")


def generate_pdf(idea, score, verdict, summary, all_results):
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 26)
    pdf.set_text_color(45, 54, 72)
    pdf.cell(0, 16, "Startup Validator Report", ln=True, align="C")

    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(120, 120, 120)
    generated_at = datetime.now().strftime("%B %d, %Y at %I:%M %p")
    pdf.cell(0, 7, f"Generated on {generated_at}", ln=True, align="C")
    pdf.ln(6)

    pdf.set_draw_color(205, 213, 224)
    pdf.line(15, pdf.get_y(), 195, pdf.get_y())
    pdf.ln(8)

    pdf.set_text_color(40, 40, 40)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, "Startup Idea", ln=True)
    pdf.set_font("Helvetica", "", 11)
    pdf.multi_cell(0, 6.5, _clean(idea))
    pdf.ln(6)

    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, "Evaluation", ln=True)

    if verdict == "Go":
        pdf.set_fill_color(5, 150, 105)
    elif verdict == "Caution":
        pdf.set_fill_color(217, 119, 6)
    else:
        pdf.set_fill_color(220, 38, 38)

    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(50, 10, f"  Score: {score}/100", fill=True, new_x="RIGHT", new_y="TOP")
    pdf.cell(5, 10, "")
    pdf.cell(40, 10, f"  {verdict}", fill=True, ln=True)
    pdf.ln(6)

    pdf.set_text_color(40, 40, 40)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, "Executive Summary", ln=True)
    pdf.set_font("Helvetica", "", 10.5)
    pdf.multi_cell(0, 6, _clean(summary))
    pdf.ln(6)

    pdf.set_draw_color(205, 213, 224)
    pdf.line(15, pdf.get_y(), 195, pdf.get_y())
    pdf.ln(6)

    pdf.set_font("Helvetica", "B", 15)
    pdf.set_text_color(45, 54, 72)
    pdf.cell(0, 10, "Detailed Agent Reports", ln=True)
    pdf.ln(3)

    agent_labels = {
        "competitor_analysis": "Competitor Analysis",
        "market_sizing": "Market Sizing",
        "community_sentiment": "Community Sentiment",
        "os_risk": "Open-Source Risk",
    }

    for result in all_results:
        agent_key = result.get("agent", "unknown")
        label = agent_labels.get(agent_key, agent_key.replace("_", " ").title())
        findings = result.get("findings", "No findings.")
        sources = result.get("sources", [])

        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(60, 60, 60)
        pdf.cell(0, 8, label, ln=True)

        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(70, 70, 70)
        pdf.multi_cell(0, 5.5, _clean(findings))

        if sources:
            pdf.set_font("Helvetica", "I", 8.5)
            pdf.set_text_color(67, 97, 238)
            for src in sources:
                link_text = _clean(f"  [{src.get('domain', '')}] {src.get('title', '')[:60]}")
                pdf.cell(0, 4.5, link_text, ln=True, link=src.get("url", ""))
            pdf.set_text_color(70, 70, 70)

        pdf.ln(5)

    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(160, 160, 160)
    pdf.cell(0, 5, "Generated by Startup Validator", ln=True, align="C")

    return bytes(pdf.output())
