import base64
import hashlib
import hmac
import json
import os
import secrets
import sqlite3
import threading
import time
from pathlib import Path
from typing import Any

import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.getenv("AUTH_DATABASE_URL") or os.getenv("DATABASE_URL")
DB_PATH = Path(os.getenv("AUTH_DB_PATH", "startup_validator.db"))
if not DB_PATH.is_absolute():
    DB_PATH = Path(__file__).resolve().parents[2] / DB_PATH
TOKEN_TTL_SECONDS = int(os.getenv("AUTH_TOKEN_TTL_SECONDS", str(60 * 60 * 24 * 7)))
TOKEN_SECRET = os.getenv("AUTH_SECRET_KEY", "dev-only-change-me")
_DB_INITIALIZED = False
_DB_INIT_LOCK = threading.Lock()


def _connect():
    if DATABASE_URL:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row)
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _execute(conn, query: str, params=()):
    if DATABASE_URL:
        query = query.replace("?", "%s")
    return conn.execute(query, params)


def _create_auth_tables():
    with _connect() as conn:
        if DATABASE_URL:
            _execute(conn, """
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL UNIQUE,
                    name TEXT NOT NULL,
                    password_hash TEXT NOT NULL,
                    created_at BIGINT NOT NULL
                )
            """)
            has_status = _execute(
                conn,
                "SELECT 1 FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = 'users' "
                "AND column_name = 'status'",
            ).fetchone()
            if not has_status:
                _execute(conn, "ALTER TABLE users ADD COLUMN status TEXT NOT NULL DEFAULT 'active'")
            _execute(conn, """
                CREATE TABLE IF NOT EXISTS validation_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    idea TEXT NOT NULL,
                    score INTEGER NOT NULL,
                    verdict TEXT NOT NULL,
                    summary TEXT NOT NULL,
                    results TEXT NOT NULL,
                    elapsed REAL NOT NULL,
                    created_at BIGINT NOT NULL
                )
            """)
            _execute(conn, "CREATE INDEX IF NOT EXISTS validation_history_user_created_idx ON validation_history (user_id, created_at DESC)")
        else:
            _execute(conn, """
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    email TEXT NOT NULL UNIQUE,
                    name TEXT NOT NULL,
                    password_hash TEXT NOT NULL,
                    created_at INTEGER NOT NULL,
                    status TEXT NOT NULL DEFAULT 'active'
                )
            """)
            columns = _execute(conn, "PRAGMA table_info(users)").fetchall()
            if not any(row["name"] == "status" for row in columns):
                _execute(conn, "ALTER TABLE users ADD COLUMN status TEXT NOT NULL DEFAULT 'active'")
            _execute(conn, """
                CREATE TABLE IF NOT EXISTS validation_history (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    idea TEXT NOT NULL,
                    score INTEGER NOT NULL,
                    verdict TEXT NOT NULL,
                    summary TEXT NOT NULL,
                    results TEXT NOT NULL,
                    elapsed REAL NOT NULL,
                    created_at INTEGER NOT NULL
                )
            """)
            _execute(conn, "CREATE INDEX IF NOT EXISTS validation_history_user_created_idx ON validation_history (user_id, created_at DESC)")


def init_auth_db():
    """Create/check application tables once per backend process."""
    global _DB_INITIALIZED
    if _DB_INITIALIZED:
        return
    with _DB_INIT_LOCK:
        if _DB_INITIALIZED:
            return
        _create_auth_tables()
        _DB_INITIALIZED = True


def save_validation(user_id: int, validation: dict[str, Any]) -> int:
    created_at = int(time.time() * 1000)
    with _connect() as conn:
        cursor = _execute(conn, """
            INSERT INTO validation_history
                (user_id, idea, score, verdict, summary, results, elapsed, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            RETURNING id
        """, (
            user_id,
            validation["idea"],
            validation["score"],
            validation["verdict"],
            validation["summary"],
            json.dumps(validation["results"]),
            validation["elapsed"],
            created_at,
        ))
        return cursor.fetchone()["id"]


def list_validations(user_id: int) -> list[dict[str, Any]]:
    with _connect() as conn:
        rows = _execute(conn, """
            SELECT id, idea, score, verdict, summary, results, elapsed, created_at
            FROM validation_history WHERE user_id = ? ORDER BY created_at DESC, id DESC
        """, (user_id,)).fetchall()
    return [{
        "historyId": row["id"],
        "idea": row["idea"],
        "score": row["score"],
        "verdict": row["verdict"],
        "summary": row["summary"],
        "results": json.loads(row["results"]),
        "elapsed": row["elapsed"],
        "cached": False,
        "savedAt": row["created_at"],
    } for row in rows]


def delete_validation(user_id: int, validation_id: int) -> bool:
    with _connect() as conn:
        cursor = _execute(conn, "DELETE FROM validation_history WHERE id = ? AND user_id = ?", (validation_id, user_id))
        return cursor.rowcount > 0


def _hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 260_000)
    return f"pbkdf2_sha256${base64.b64encode(salt).decode()}${base64.b64encode(digest).decode()}"


def _verify_password(password: str, stored_hash: str) -> bool:
    try:
        algorithm, encoded_salt, encoded_digest = stored_hash.split("$", 2)
    except ValueError:
        return False

    if algorithm != "pbkdf2_sha256":
        return False

    salt = base64.b64decode(encoded_salt)
    expected = base64.b64decode(encoded_digest)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 260_000)
    return hmac.compare_digest(digest, expected)


def _public_user(row) -> dict[str, Any]:
    return {
        "id": row["id"],
        "email": row["email"],
        "name": row["name"],
        "created_at": row["created_at"],
        "status": row["status"],
    }


def _email_exists(email: str) -> bool:
    with _connect() as conn:
        return _execute(conn, "SELECT 1 FROM users WHERE email = ?", (email,)).fetchone() is not None


def _insert_user(email: str, name: str, password_hash: str) -> dict[str, Any]:
    with _connect() as conn:
        cursor = _execute(
            conn,
            """
            INSERT INTO users (email, name, password_hash, created_at)
            VALUES (?, ?, ?, ?)
            RETURNING id
            """,
            (email, name, password_hash, int(time.time())),
        )
        user_id = cursor.fetchone()["id"]
        row = _execute(conn, "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
        return _public_user(row)


def _sync_postgres_user_id_sequence():
    with _connect() as conn:
        _execute(
            conn,
            """
            SELECT setval(
                pg_get_serial_sequence('users', 'id'),
                GREATEST(COALESCE((SELECT MAX(id) FROM users), 1), 1),
                EXISTS (SELECT 1 FROM users)
            )
            """,
        )


def create_user(email: str, name: str, password: str) -> dict[str, Any]:
    normalized_email = email.strip().lower()
    clean_name = name.strip() or normalized_email.split("@")[0]
    password_hash = _hash_password(password)

    try:
        return _insert_user(normalized_email, clean_name, password_hash)
    except sqlite3.IntegrityError as exc:
        if _email_exists(normalized_email):
            raise ValueError("An account with that email already exists.") from exc
        raise
    except psycopg.errors.UniqueViolation as exc:
        if _email_exists(normalized_email):
            raise ValueError("An account with that email already exists.") from exc
        if exc.diag.constraint_name and exc.diag.constraint_name.endswith("_pkey"):
            _sync_postgres_user_id_sequence()
            try:
                return _insert_user(normalized_email, clean_name, password_hash)
            except psycopg.errors.UniqueViolation as retry_exc:
                if _email_exists(normalized_email):
                    raise ValueError("An account with that email already exists.") from retry_exc
                raise
        raise


def authenticate_user(email: str, password: str) -> dict[str, Any] | None:
    with _connect() as conn:
        row = _execute(conn, "SELECT * FROM users WHERE email = ?", (email.strip().lower(),)).fetchone()

    if not row or row["status"] != "active" or not _verify_password(password, row["password_hash"]):
        return None

    return _public_user(row)


def get_user(user_id: int) -> dict[str, Any] | None:
    with _connect() as conn:
        row = _execute(conn, "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
    return _public_user(row) if row else None


def issue_token(user: dict[str, Any]) -> str:
    payload = {
        "sub": user["id"],
        "email": user["email"],
        "exp": int(time.time()) + TOKEN_TTL_SECONDS,
    }
    payload_json = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8")
    encoded_payload = base64.urlsafe_b64encode(payload_json).decode().rstrip("=")
    signature = hmac.new(TOKEN_SECRET.encode("utf-8"), encoded_payload.encode("utf-8"), hashlib.sha256).digest()
    encoded_signature = base64.urlsafe_b64encode(signature).decode().rstrip("=")
    return f"{encoded_payload}.{encoded_signature}"


def verify_token(token: str) -> dict[str, Any] | None:
    try:
        encoded_payload, encoded_signature = token.split(".", 1)
        expected_signature = hmac.new(
            TOKEN_SECRET.encode("utf-8"),
            encoded_payload.encode("utf-8"),
            hashlib.sha256,
        ).digest()
        actual_signature = base64.urlsafe_b64decode(encoded_signature + "=" * (-len(encoded_signature) % 4))
    except (ValueError, TypeError):
        return None

    if not hmac.compare_digest(actual_signature, expected_signature):
        return None

    try:
        payload_bytes = base64.urlsafe_b64decode(encoded_payload + "=" * (-len(encoded_payload) % 4))
        payload = json.loads(payload_bytes)
    except (ValueError, json.JSONDecodeError):
        return None

    if payload.get("exp", 0) < time.time():
        return None

    user_id = payload.get("sub")
    if not isinstance(user_id, int):
        return None

    user = get_user(user_id)
    return user if user and user["status"] == "active" else None



def update_user(user_id: int, name: str, email: str) -> dict[str, Any]:
    normalized_email = email.strip().lower()
    clean_name = name.strip()
    try:
        with _connect() as conn:
            taken = _execute(
                conn,
                "SELECT 1 FROM users WHERE email = ? AND id <> ?",
                (normalized_email, user_id),
            ).fetchone()
            if taken:
                raise ValueError("An account with that email already exists.")
            _execute(
                conn,
                "UPDATE users SET name = ?, email = ? WHERE id = ?",
                (clean_name, normalized_email, user_id),
            )
            row = _execute(conn, "SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
    except (sqlite3.IntegrityError, psycopg.errors.UniqueViolation) as exc:
        raise ValueError("An account with that email already exists.") from exc
    if not row:
        raise ValueError("User not found.")
    return _public_user(row)


def change_user_password(user_id: int, current: str, new: str) -> bool:
    with _connect() as conn:
        row = _execute(
            conn, "SELECT password_hash FROM users WHERE id = ?", (user_id,)
        ).fetchone()
        if not row or not _verify_password(current, row["password_hash"]):
            return False
        _execute(
            conn,
            "UPDATE users SET password_hash = ? WHERE id = ?",
            (_hash_password(new), user_id),
        )
    return True